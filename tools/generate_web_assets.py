#!/usr/bin/env python3
"""Generate deterministic flash-resident gzip assets from the actual UI header.

Usable as a PlatformIO pre-script or a dependency-free command-line utility.
The small scanner supports only raw C++ strings and the three UI macros used
by web_ui.h; unexpected expressions fail the build instead of changing pages.
"""
from __future__ import annotations

import argparse
import gzip
import hashlib
import io
from pathlib import Path
import re
import tempfile


SCRIPT = Path(globals().get("__file__") or Path.cwd() / "tools" / "generate_web_assets.py").resolve()
ROOT = SCRIPT.parents[1]
ASSETS = ("INDEX_HTML", "HUB_HTML")


def render_asset(source: str, name: str, channels: int, hostname: str) -> bytes:
    if channels not in (1, 2):
        raise ValueError("LED_CHANNELS must be 1 or 2")
    if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9-]{0,62}", hostname):
        raise ValueError("LED_HOSTNAME must be a DNS hostname label")
    macros = {
        "LED_UI_CHANNELS": str(channels),
        "LED_UI_DEVICE_NAME": "led-szallag" if channels == 1 else "terrárium",
        "LED_HOSTNAME": hostname,
    }
    declaration = re.search(r"\bconst\s+char\s+" + re.escape(name) + r"\[\]\s+PROGMEM\s*=", source)
    if not declaration:
        raise ValueError(f"Missing {name} declaration")
    position, pieces = declaration.end(), []
    while position < len(source):
        if source[position].isspace():
            position += 1
            continue
        if source[position] == ";":
            return "".join(pieces).encode("utf-8")
        if source.startswith('R"', position):
            opening = source.find("(", position + 2)
            delimiter = source[position + 2:opening]
            if opening < 0 or len(delimiter) > 16 or re.search(r'[\s()\\]', delimiter):
                raise ValueError(f"Invalid C++ raw string in {name}")
            closing = ")" + delimiter + '"'
            end = source.find(closing, opening + 1)
            if end < 0:
                raise ValueError(f"Unterminated C++ raw string in {name}")
            pieces.append(source[opening + 1:end])
            position = end + len(closing)
            continue
        token = re.match(r"[A-Za-z_][A-Za-z0-9_]*", source[position:])
        if not token or token.group() not in macros:
            raise ValueError(f"Unsupported token in {name} at character {position}")
        pieces.append(macros[token.group()])
        position += len(token.group())
    raise ValueError(f"Unterminated {name} declaration")


def gzip_bytes(data: bytes) -> bytes:
    output = io.BytesIO()
    # GzipFile avoids platform-dependent OS header bytes in gzip.compress on
    # some Python versions, and never embeds a filename or current timestamp.
    with gzip.GzipFile(filename="", fileobj=output, mode="wb", compresslevel=9, mtime=0) as stream:
        stream.write(data)
    return output.getvalue()


def generate(source_path: Path, output_path: Path, channels: int, hostname: str) -> dict[str, tuple[int, int]]:
    source = source_path.read_text(encoding="utf-8")
    lines = ["// Generated by tools/generate_web_assets.py; do not edit.",
             "#pragma once", "#include <Arduino.h>",
             "// Source SHA256: " + hashlib.sha256(source.encode("utf-8")).hexdigest()]
    sizes = {}
    for name in ASSETS:
        raw = render_asset(source, name, channels, hostname)
        compressed = gzip_bytes(raw)
        sizes[name] = (len(raw), len(compressed))
        lines.extend([f"// {name}: {len(raw)} -> {len(compressed)} bytes.",
                      f"const unsigned char {name}_GZIP[] PROGMEM = {{"])
        for start in range(0, len(compressed), 16):
            lines.append("  " + ",".join(f"0x{byte:02x}" for byte in compressed[start:start + 16]) + ",")
        lines.append("};")
    content = "\n".join(lines) + "\n"
    if output_path.exists() and output_path.read_text(encoding="utf-8") == content:
        return sizes
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", dir=output_path.parent,
                                     prefix=output_path.name + ".", delete=False) as stream:
        temporary = Path(stream.name)
        stream.write(content)
    temporary.replace(output_path)
    return sizes


def build_defines(environment) -> dict[str, str]:
    definitions = list(environment.get("CPPDEFINES", []))
    definitions += environment.ParseFlags(environment.get("BUILD_FLAGS", [])).get("CPPDEFINES", [])
    result = {}
    for definition in definitions:
        if isinstance(definition, (list, tuple)):
            key, value = definition[0], str(definition[1]) if len(definition) > 1 else "1"
        else:
            key, _, value = str(definition).partition("=")
        result[str(key)] = value
    return result


def install(environment) -> None:
    definitions = build_defines(environment)
    channels = int(definitions.get("LED_CHANNELS", "2"))
    hostname = definitions.get("LED_HOSTNAME", "led-control").replace('\\"', '"').strip('"')
    directory = Path(environment.subst("$BUILD_DIR")) / "generated"
    header = directory / "web_assets.h"
    source = Path(environment.subst("$PROJECT_DIR")) / "src" / "web_ui.h"
    generate(source, header, channels, hostname)
    environment.Append(CPPPATH=[str(directory)])
    # The normal C++ include scanner also tracks the header. Explicitly attach
    # the source header/script so an asset change always invalidates main.o.
    environment.Depends("$BUILD_DIR/src/main.cpp.o", [str(header), str(source), str(SCRIPT)])


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--channels", type=int, choices=(1, 2), default=2)
    parser.add_argument("--hostname", default="led-control")
    parser.add_argument("--source", type=Path, default=ROOT / "src" / "web_ui.h")
    parser.add_argument("--output", type=Path, required=True)
    options = parser.parse_args()
    for name, sizes in generate(options.source, options.output, options.channels, options.hostname).items():
        print(f"{name}: {sizes[0]} -> {sizes[1]} bytes")


if "Import" in globals():
    Import("env")  # type: ignore[name-defined]  # PlatformIO/SCons injects Import.
    install(env)  # type: ignore[name-defined]
elif __name__ == "__main__":
    main()
